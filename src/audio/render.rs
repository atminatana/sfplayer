//! The real-time render core: runs inside the cpal callback. No allocation, no locking, no I/O here.
//!
//! Two inbound rings feed the renderer: MIDI events from the MIDI thread and `Command`s from the UI
//! thread (ADR 0002, 0009). Replaced engines travel back to the UI thread through the `retired` ring
//! so that deallocation never happens on the audio thread.

use std::sync::Arc;
use std::time::Instant;

use ringbuf::traits::{Consumer, Producer};
use ringbuf::{HeapCons, HeapProd};

use super::AudioShared;
use super::meter::measure;
use crate::midi::{MidiEvent, controller};
use crate::synth::SynthEngine;

/// Frames rendered per inner pass; larger callbacks are processed in chunks of this size.
pub const MAX_CHUNK_FRAMES: usize = 4096;

/// Instructions from the UI thread to the audio thread.
pub enum Command {
	/// A note or controller generated by the UI (text keyboard, panic) — same path as hardware MIDI.
	Midi(MidiEvent),
	/// Swap the synthesizer; `None` silences the output. The previous engine is returned via the retired ring.
	ReplaceEngine(Option<Box<dyn SynthEngine>>),
}

pub struct BlockRenderer {
	engine: Option<Box<dyn SynthEngine>>,
	events: HeapCons<MidiEvent>,
	commands: HeapCons<Command>,
	retired: HeapProd<Box<dyn SynthEngine>>,
	shared: Arc<AudioShared>,
	sample_rate: u32,
	left: Vec<f32>,
	right: Vec<f32>,
	/// Bit per key, per channel: which notes are held (F-12 "voices").
	held: [u128; 16],
	held_count: u32,
	/// Key actually sounding for each (channel, played key), so a note off matches its note on even if the
	/// transposition changed in between (F-15).
	sounding: [[u8; 128]; 16],
}

impl BlockRenderer {
	/// Allocates the scratch buffers once; everything after this is allocation-free.
	pub fn new(
		events: HeapCons<MidiEvent>,
		commands: HeapCons<Command>,
		retired: HeapProd<Box<dyn SynthEngine>>,
		shared: Arc<AudioShared>,
		sample_rate: u32,
	) -> Self {
		Self {
			engine: None,
			events,
			commands,
			retired,
			shared,
			sample_rate,
			left: vec![0.0; MAX_CHUNK_FRAMES],
			right: vec![0.0; MAX_CHUNK_FRAMES],
			held: [0; 16],
			held_count: 0,
			sounding: [[0; 128]; 16],
		}
	}

	/// Applies omni redirection (hardware MIDI only) and transposition before tracking and the engine.
	fn prepare(&mut self, event: MidiEvent, from_hardware: bool) -> MidiEvent {
		let event = match (from_hardware, self.shared.omni_channel(), event) {
			(true, Some(target), MidiEvent::NoteOn { key, velocity, .. }) => MidiEvent::NoteOn {
				channel: target,
				key,
				velocity,
			},
			(true, Some(target), MidiEvent::NoteOff { key, .. }) => MidiEvent::NoteOff { channel: target, key },
			(_, _, event) => event,
		};
		let transpose = self.shared.transpose();
		match event {
			MidiEvent::NoteOn { channel, key, velocity } => {
				let sounding = (i16::from(key) + i16::from(transpose)).clamp(0, 127) as u8;
				if let Some(map) = self.sounding.get_mut(usize::from(channel)) {
					map[usize::from(key & 0x7F)] = sounding;
				}
				MidiEvent::NoteOn {
					channel,
					key: sounding,
					velocity,
				}
			}
			MidiEvent::NoteOff { channel, key } => {
				let sounding = self
					.sounding
					.get(usize::from(channel))
					.map_or(key, |map| map[usize::from(key & 0x7F)]);
				MidiEvent::NoteOff { channel, key: sounding }
			}
			other => other,
		}
	}

	/// Fills an interleaved output buffer with `channels` channels per frame.
	/// Channels beyond the first two are silent; a mono output gets the L/R average.
	pub fn fill(&mut self, output: &mut [f32], channels: usize) {
		// Clock reads are user-mode on every supported platform (QPC / vDSO), so they are allowed here (N-03).
		let started = Instant::now();
		self.drain_commands();
		self.drain_events();
		let total_frames = output.len() / channels.max(1);
		match self.engine.as_mut() {
			None => output.fill(0.0),
			Some(engine) => {
				let gain = self.shared.master_gain();
				for chunk in output.chunks_mut(MAX_CHUNK_FRAMES * channels) {
					let frames = chunk.len() / channels;
					engine.render(&mut self.left[..frames], &mut self.right[..frames]);
					let (levels, clipped) = measure(&self.left[..frames], &self.right[..frames], gain);
					self.shared.publish_levels(levels, clipped);
					interleave(&self.left[..frames], &self.right[..frames], gain, chunk, channels);
				}
			}
		}
		self.shared.publish_stats(
			self.held_count,
			load_percent(started.elapsed().as_secs_f32(), total_frames, self.sample_rate),
		);
	}

	/// Keeps the held-note bitmap in sync with what reaches the engine.
	fn track(&mut self, event: MidiEvent) {
		match event {
			MidiEvent::NoteOn { channel, key, .. } => {
				if let Some(bits) = self.held.get_mut(usize::from(channel)) {
					let mask = 1u128 << (key & 0x7F);
					if *bits & mask == 0 {
						*bits |= mask;
						self.held_count += 1;
					}
				}
			}
			MidiEvent::NoteOff { channel, key } => {
				if let Some(bits) = self.held.get_mut(usize::from(channel)) {
					let mask = 1u128 << (key & 0x7F);
					if *bits & mask != 0 {
						*bits &= !mask;
						self.held_count -= 1;
					}
				}
			}
			MidiEvent::ControlChange { channel, controller, .. }
				if controller == controller::ALL_NOTES_OFF || controller == controller::ALL_SOUND_OFF =>
			{
				if let Some(bits) = self.held.get_mut(usize::from(channel)) {
					self.held_count -= bits.count_ones();
					*bits = 0;
				}
			}
			_ => {}
		}
	}

	fn reset_held(&mut self) {
		self.held = [0; 16];
		self.held_count = 0;
	}

	fn drain_commands(&mut self) {
		while let Some(command) = self.commands.try_pop() {
			match command {
				Command::Midi(event) => {
					let event = self.prepare(event, false);
					self.track(event);
					if let Some(engine) = self.engine.as_mut() {
						apply_event(engine.as_mut(), event);
					}
				}
				Command::ReplaceEngine(next) => {
					self.reset_held();
					self.shared
						.set_max_voices(next.as_ref().map_or(0, |engine| engine.max_voices() as u32));
					if let Some(previous) = std::mem::replace(&mut self.engine, next) {
						// A full retired ring means the UI thread is not draining; dropping here is the
						// lesser evil compared to leaking, and only happens in that degenerate case.
						let _ = self.retired.try_push(previous);
					}
				}
			}
		}
	}

	fn drain_events(&mut self) {
		while let Some(event) = self.events.try_pop() {
			let event = self.prepare(event, true);
			self.track(event);
			if let Some(engine) = self.engine.as_mut() {
				apply_event(engine.as_mut(), event);
			}
		}
	}
}

fn apply_event(engine: &mut dyn SynthEngine, event: MidiEvent) {
	match event {
		MidiEvent::NoteOn { channel, key, velocity } => engine.note_on(channel, key, velocity),
		MidiEvent::NoteOff { channel, key } => engine.note_off(channel, key),
		MidiEvent::ControlChange {
			channel,
			controller,
			value,
		} => engine.control_change(channel, controller, value),
		MidiEvent::ProgramChange { channel, program } => engine.program_change(channel, program),
		MidiEvent::PitchBend { channel, value } => engine.pitch_bend(channel, value),
		// rustysynth has no channel pressure generator; spec F-07 lists it as handled, so it is consumed here, not logged.
		MidiEvent::ChannelPressure { .. } | MidiEvent::Other { .. } => {}
	}
}

/// Callback duration relative to the audio time of the block, in percent (F-12 "cpu").
fn load_percent(elapsed_seconds: f32, frames: usize, sample_rate: u32) -> u32 {
	if frames == 0 || sample_rate == 0 {
		return 0;
	}
	let block_seconds = frames as f32 / sample_rate as f32;
	(elapsed_seconds / block_seconds * 100.0).round().clamp(0.0, 999.0) as u32
}

fn interleave(left: &[f32], right: &[f32], gain: f32, output: &mut [f32], channels: usize) {
	for (frame, out) in output.chunks_mut(channels).enumerate() {
		let (l, r) = (left[frame] * gain, right[frame] * gain);
		match out {
			[mono] => *mono = (l + r) * 0.5,
			[first, second, rest @ ..] => {
				*first = l;
				*second = r;
				rest.fill(0.0);
			}
			[] => {}
		}
	}
}

#[cfg(test)]
mod tests {
	use std::path::Path;

	use ringbuf::HeapRb;
	use ringbuf::traits::Split;

	use super::*;
	use crate::synth::test_support::{TEST_BANK_PATH, rms};
	use crate::synth::{RustySynthEngine, SoundFontBank};

	const SAMPLE_RATE: u32 = 48_000;
	const FRAMES: usize = 4_800;
	const RING_CAPACITY: usize = 16;
	const NOTE_ON: MidiEvent = MidiEvent::NoteOn {
		channel: 0,
		key: 60,
		velocity: 100,
	};

	struct Harness {
		renderer: BlockRenderer,
		events: HeapProd<MidiEvent>,
		commands: HeapProd<Command>,
		retired: HeapCons<Box<dyn SynthEngine>>,
		shared: Arc<AudioShared>,
	}

	fn engine() -> Box<dyn SynthEngine> {
		let bank = SoundFontBank::load(Path::new(TEST_BANK_PATH)).expect("test bank loads");
		Box::new(RustySynthEngine::new(&bank, SAMPLE_RATE).expect("engine"))
	}

	/// Renderer with an engine already installed through the command ring.
	fn harness() -> Harness {
		let mut harness = empty_harness();
		harness.commands.try_push(Command::ReplaceEngine(Some(engine()))).ok().unwrap();
		harness
	}

	fn empty_harness() -> Harness {
		let shared = Arc::new(AudioShared::default());
		let (events, events_rx) = HeapRb::<MidiEvent>::new(RING_CAPACITY).split();
		let (commands, commands_rx) = HeapRb::<Command>::new(RING_CAPACITY).split();
		let (retired_tx, retired) = HeapRb::<Box<dyn SynthEngine>>::new(RING_CAPACITY).split();
		let renderer = BlockRenderer::new(events_rx, commands_rx, retired_tx, Arc::clone(&shared), SAMPLE_RATE);
		Harness {
			renderer,
			events,
			commands,
			retired,
			shared,
		}
	}

	fn deinterleave(output: &[f32], channels: usize) -> (Vec<f32>, Vec<f32>) {
		let left = output.iter().step_by(channels).copied().collect();
		let right = output.iter().skip(1).step_by(channels).copied().collect();
		(left, right)
	}

	#[test]
	fn no_engine_means_silence_even_with_events() {
		let mut h = empty_harness();
		h.events.try_push(NOTE_ON).unwrap();
		let mut output = vec![1.0; FRAMES * 2];
		h.renderer.fill(&mut output, 2);
		assert!(output.iter().all(|sample| *sample == 0.0));
	}

	#[test]
	fn silence_without_events() {
		let mut h = harness();
		let mut output = vec![1.0; FRAMES * 2];
		h.renderer.fill(&mut output, 2);
		assert!(output.iter().all(|sample| *sample == 0.0));
	}

	#[test]
	fn note_from_midi_ring_is_rendered_to_both_stereo_channels() {
		let mut h = harness();
		h.events.try_push(NOTE_ON).unwrap();
		let mut output = vec![0.0; FRAMES * 2];
		h.renderer.fill(&mut output, 2);
		let (left, right) = deinterleave(&output, 2);
		assert!(rms(&left) > 0.01, "left {}", rms(&left));
		assert!(rms(&right) > 0.01, "right {}", rms(&right));
	}

	#[test]
	fn note_from_command_ring_takes_the_same_path() {
		let mut h = harness();
		h.commands.try_push(Command::Midi(NOTE_ON)).ok().unwrap();
		let mut output = vec![0.0; FRAMES * 2];
		h.renderer.fill(&mut output, 2);
		assert!(rms(&output) > 0.01);
	}

	#[test]
	fn replacing_the_engine_returns_the_old_one_through_the_retired_ring() {
		let mut h = harness();
		let mut output = vec![0.0; FRAMES * 2];
		h.renderer.fill(&mut output, 2);
		assert!(h.retired.try_pop().is_none());
		h.commands.try_push(Command::ReplaceEngine(None)).ok().unwrap();
		h.events.try_push(NOTE_ON).unwrap();
		h.renderer.fill(&mut output, 2);
		assert!(h.retired.try_pop().is_some(), "old engine handed back");
		assert!(output.iter().all(|sample| *sample == 0.0), "no engine → silence");
	}

	#[test]
	fn levels_are_published_after_each_block() {
		let mut h = harness();
		h.events.try_push(NOTE_ON).unwrap();
		let mut output = vec![0.0; FRAMES * 2];
		h.renderer.fill(&mut output, 2);
		let levels = h.shared.levels();
		assert!(levels.peak_left > 0.01 && levels.rms_left > 0.01, "{levels:?}");
		assert!(levels.peak_left >= levels.rms_left);
		h.shared.set_master_gain(0.0);
		h.renderer.fill(&mut output, 2);
		assert_eq!(h.shared.levels(), crate::audio::Levels::default(), "levels follow the master gain");
		assert_eq!(h.shared.clips(), 0);
	}

	#[test]
	fn held_notes_follow_note_on_off_all_notes_off_and_engine_swap() {
		let mut h = harness();
		let mut output = vec![0.0; FRAMES * 2];
		h.renderer.fill(&mut output, 2);
		assert_eq!(h.shared.max_voices(), 64, "polyphony of the installed engine");
		h.events.try_push(NOTE_ON).unwrap();
		h.events
			.try_push(MidiEvent::NoteOn {
				channel: 1,
				key: 64,
				velocity: 80,
			})
			.unwrap();
		h.events.try_push(NOTE_ON).unwrap();
		h.renderer.fill(&mut output, 2);
		assert_eq!(h.shared.held_notes(), 2, "a repeated note on counts once");
		h.commands
			.try_push(Command::Midi(MidiEvent::NoteOff { channel: 0, key: 60 }))
			.ok()
			.unwrap();
		h.renderer.fill(&mut output, 2);
		assert_eq!(h.shared.held_notes(), 1);
		h.events
			.try_push(MidiEvent::ControlChange {
				channel: 1,
				controller: 123,
				value: 0,
			})
			.unwrap();
		h.renderer.fill(&mut output, 2);
		assert_eq!(h.shared.held_notes(), 0);
		h.events.try_push(NOTE_ON).unwrap();
		h.commands.try_push(Command::ReplaceEngine(None)).ok().unwrap();
		h.renderer.fill(&mut output, 2);
		assert_eq!(
			h.shared.held_notes(),
			1,
			"note on arrives after the swap and is tracked without an engine"
		);
		assert_eq!(h.shared.max_voices(), 0);
	}

	#[test]
	fn transposed_note_off_matches_its_note_on_even_after_the_transpose_changes() {
		let mut h = harness();
		let mut output = vec![0.0; FRAMES * 2];
		h.shared.set_transpose(12);
		h.events.try_push(NOTE_ON).unwrap();
		h.renderer.fill(&mut output, 2);
		assert!(rms(&output) > 0.01);
		h.shared.set_transpose(0);
		h.events.try_push(MidiEvent::NoteOff { channel: 0, key: 60 }).unwrap();
		let mut tail = vec![0.0; SAMPLE_RATE as usize * 2];
		h.renderer.fill(&mut tail, 2);
		h.renderer.fill(&mut output, 2);
		assert!(rms(&output) < 0.001, "note off reached the transposed key: {}", rms(&output));
	}

	#[test]
	fn omni_redirects_hardware_notes_but_not_ui_notes() {
		let mut h = harness();
		let mut output = vec![0.0; FRAMES * 2];
		h.shared.set_omni_channel(Some(0));
		h.events
			.try_push(MidiEvent::NoteOn {
				channel: 5,
				key: 60,
				velocity: 100,
			})
			.unwrap();
		h.renderer.fill(&mut output, 2);
		assert!(rms(&output) > 0.01);
		h.events
			.try_push(MidiEvent::ControlChange {
				channel: 0,
				controller: 123,
				value: 0,
			})
			.unwrap();
		let mut tail = vec![0.0; SAMPLE_RATE as usize * 2];
		h.renderer.fill(&mut tail, 2);
		h.renderer.fill(&mut output, 2);
		assert!(
			rms(&output) < 0.001,
			"the note sounded on channel 0, so all-notes-off there silences it"
		);
		h.commands
			.try_push(Command::Midi(MidiEvent::NoteOn {
				channel: 5,
				key: 60,
				velocity: 100,
			}))
			.ok()
			.unwrap();
		h.renderer.fill(&mut output, 2);
		h.events
			.try_push(MidiEvent::ControlChange {
				channel: 0,
				controller: 123,
				value: 0,
			})
			.unwrap();
		h.renderer.fill(&mut tail, 2);
		h.renderer.fill(&mut output, 2);
		assert!(
			rms(&output) > 0.001,
			"UI notes keep their channel: all-notes-off on channel 0 leaves channel 5 playing"
		);
	}

	#[test]
	fn load_percent_relates_callback_time_to_block_time() {
		assert_eq!(load_percent(0.001, 480, 48_000), 10);
		assert_eq!(load_percent(0.5, 480, 48_000), 999, "clamped");
		assert_eq!(load_percent(0.1, 0, 48_000), 0);
		let mut h = harness();
		let mut output = vec![0.0; FRAMES * 2];
		h.renderer.fill(&mut output, 2);
		assert!(h.shared.load_percent() <= 999);
	}

	#[test]
	fn master_gain_scales_output() {
		let mut h = harness();
		h.events.try_push(NOTE_ON).unwrap();
		h.shared.set_master_gain(0.0);
		let mut output = vec![0.0; FRAMES * 2];
		h.renderer.fill(&mut output, 2);
		assert!(output.iter().all(|sample| *sample == 0.0));
	}

	#[test]
	fn mono_output_mixes_both_sides() {
		let mut h = harness();
		h.events.try_push(NOTE_ON).unwrap();
		let mut output = vec![0.0; FRAMES];
		h.renderer.fill(&mut output, 1);
		assert!(rms(&output) > 0.01);
	}

	#[test]
	fn extra_channels_are_silent() {
		let mut h = harness();
		h.events.try_push(NOTE_ON).unwrap();
		let mut output = vec![1.0; FRAMES * 4];
		h.renderer.fill(&mut output, 4);
		let third: Vec<f32> = output.iter().skip(2).step_by(4).copied().collect();
		let fourth: Vec<f32> = output.iter().skip(3).step_by(4).copied().collect();
		assert!(third.iter().chain(&fourth).all(|sample| *sample == 0.0));
		let (left, _) = deinterleave(&output, 4);
		assert!(rms(&left) > 0.01);
	}

	#[test]
	fn buffers_larger_than_chunk_are_processed_whole() {
		let mut h = harness();
		h.events.try_push(NOTE_ON).unwrap();
		let frames = MAX_CHUNK_FRAMES * 2 + 123;
		let mut output = vec![0.0; frames * 2];
		h.renderer.fill(&mut output, 2);
		let tail = &output[output.len() - 200..];
		assert!(rms(tail) > 0.01, "tail of a long buffer must still carry sound");
	}

	#[test]
	fn note_off_event_is_applied() {
		let mut h = harness();
		h.events.try_push(NOTE_ON).unwrap();
		let mut output = vec![0.0; FRAMES * 2];
		h.renderer.fill(&mut output, 2);
		h.events.try_push(MidiEvent::NoteOff { channel: 0, key: 60 }).unwrap();
		let mut tail = vec![0.0; SAMPLE_RATE as usize * 2];
		h.renderer.fill(&mut tail, 2);
		h.renderer.fill(&mut output, 2);
		assert!(rms(&output) < 0.001, "after note off {}", rms(&output));
	}
}
